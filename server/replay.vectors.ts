/**
 * Golden targets: `(seed, roundIndex, difficulty)` → the exact OKLCh triple.
 *
 * **These are our own output, deliberately.** CLAUDE.md forbids pinning a test to
 * whatever the implementation currently returns, because for colour science the
 * published reference value is the truth and ours is the thing under test. This
 * file is the one legitimate exception, and the reason is that it is not testing
 * colour science at all — it is testing *engine agreement*.
 *
 * ADR 0016 rests on a claim: that the client and the Worker, running the same pure
 * `generateTarget`, produce bit-identical targets. `makeRng` is integer-only and
 * `nextInRange` is one IEEE multiply-add, so lightness, hue and the chroma
 * fraction are exact everywhere. Only `maxChroma`'s bisection can diverge, and its
 * own 1e-6 tolerance bounds that at ~4000× below an 8-bit code step.
 *
 * That is an argument. This file makes it a build gate. The same literals are
 * asserted with `toBe` — bit equality, never `toBeCloseTo`, because "close" is
 * exactly the failure being hunted — under happy-dom (V8), Node (V8), a real
 * browser, and workerd. If a future V8 changes `cbrt`, or someone ships a
 * "harmless" refactor of the gamut bisection, this is what fires.
 *
 * Tuples rather than objects purely so one vector is one line and the whole set
 * stays readable. Regenerate only when target generation changes *on purpose*, and
 * say so in the commit message — a silent regeneration defeats the point.
 */

